import { randomUUID } from "node:crypto";
import { test, expect } from "@playwright/test";

test("real multiple boards retain names, cards, selection and isolation through reload and login", async ({ page, baseURL }, testInfo) => {
  test.skip(process.env.KANBAN_DISPOSABLE_E2E !== "1" || testInfo.project.name !== "desktop", "Explicit disposable-database acceptance check; creates an additional board.");
  expect(baseURL).toBe("http://localhost:8002");
  const name = `Acceptance board ${randomUUID().slice(0, 8)}`;
  await page.request.post("/api/auth/login", { data: { username: "user", password: "password" } });
  const first = (await (await page.request.get("/api/boards")).json())[0];
  const original = await (await page.request.get(`/api/boards/${first.id}`)).json();
  await page.goto("/");
  await page.getByRole("button", { name: "New board", exact: true }).click();
  await page.getByLabel("Board name", { exact: true }).fill(name);
  await page.getByRole("button", { name: "Create board", exact: true }).click();
  await expect(page.getByRole("heading", { name: `${name}.`, exact: true })).toBeVisible();
  const second = Number(new URL(page.url()).searchParams.get("board"));
  expect(second).not.toBe(first.id);
  await expect(page.getByRole("article")).toHaveCount(0);
  await page.getByRole("button", { name: "Add card to Backlog" }).click();
  await page.getByLabel("Title", { exact: true }).fill(name);
  await page.getByLabel("Details", { exact: true }).fill("Only on the selected board");
  await page.getByRole("button", { name: "Create card", exact: true }).click();
  await expect(page.getByRole("article", { name, exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "Rename Review" }).fill("Second-board review");
  await page.getByRole("textbox", { name: "Rename Review" }).press("Enter");
  await expect(page.getByRole("region", { name: "Second-board review column" })).toBeVisible();
  await page.getByRole("button", { name: "Rename board", exact: true }).click();
  await page.getByLabel("Board name", { exact: true }).fill(`Renamed ${name}`);
  await page.getByRole("button", { name: "Save board name" }).click();
  await expect(page.getByRole("heading", { name: `Renamed ${name}.`, exact: true })).toBeVisible();
  await page.getByLabel("Board", { exact: true }).selectOption(String(first.id));
  await expect(page.getByRole("heading", { name: `${first.name}.`, exact: true })).toBeVisible();
  expect(await (await page.request.get(`/api/boards/${first.id}`)).json()).toEqual(original);
  await expect(page.getByRole("article", { name, exact: true })).toHaveCount(0);
  await page.getByLabel("Board", { exact: true }).selectOption(String(second));
  await page.reload();
  await expect(page.getByRole("article", { name, exact: true })).toContainText("Only on the selected board");
  await expect(page.getByRole("region", { name: "Second-board review column" })).toBeVisible();
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await page.getByLabel("Username", { exact: true }).fill("user");
  await page.getByLabel("Password", { exact: true }).fill("password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: `Renamed ${name}.`, exact: true })).toBeVisible();
  await expect(page.getByRole("article", { name, exact: true })).toBeVisible();
  await page.getByRole("button", { name: `Delete ${name}`, exact: true }).click();
  await page.reload();
  await expect(page.getByRole("heading", { name: `Renamed ${name}.`, exact: true })).toBeVisible();
  await expect(page.getByRole("article", { name, exact: true })).toHaveCount(0);
  expect(await (await page.request.get(`/api/boards/${first.id}`)).json()).toEqual(original);
});
